/**
 * Логгер приложения.
 * В production выводит только предупреждения и ошибки.
 * console.log запрещён — используйте этот модуль.
 */

type Уровень = 'отладка' | 'инфо' | 'предупреждение' | 'ошибка';

const УРОВНИ: Record<Уровень, number> = {
  отладка: 0,
  инфо: 1,
  предупреждение: 2,
  ошибка: 3,
};

const МИНИМУМ: Уровень =
  import.meta.env.DEV ? 'отладка' : 'предупреждение';

function форматировать(уровень: Уровень, сообщение: string, данные?: unknown): void {
  if (УРОВНИ[уровень] < УРОВНИ[МИНИМУМ]) return;

  const префикс = `[PDF Layout Inspector · ${уровень}]`;
  const метод =
    уровень === 'ошибка'
      ? console.error
      : уровень === 'предупреждение'
        ? console.warn
        : console.info;

  if (данные !== undefined) {
    метод(префикс, сообщение, данные);
  } else {
    метод(префикс, сообщение);
  }
}

export const логгер = {
  отладка(сообщение: string, данные?: unknown): void {
    форматировать('отладка', сообщение, данные);
  },
  инфо(сообщение: string, данные?: unknown): void {
    форматировать('инфо', сообщение, данные);
  },
  предупреждение(сообщение: string, данные?: unknown): void {
    форматировать('предупреждение', сообщение, данные);
  },
  ошибка(сообщение: string, данные?: unknown): void {
    форматировать('ошибка', сообщение, данные);
  },
};
