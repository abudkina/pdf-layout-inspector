import {
  НАСТРОЙКИ_ПО_УМОЛЧАНИЮ,
  type НастройкиПриложения,
  type СтраницаПриложения,
} from '../types';
import { логгер } from './logger';
import { ограничить } from './validation';

const КЛЮЧ = 'pdf-layout-inspector:настройки';

/**
 * Сохранение и загрузка настроек в LocalStorage.
 */
export function загрузитьНастройки(): НастройкиПриложения {
  try {
    const сырое = localStorage.getItem(КЛЮЧ);
    if (!сырое) return { ...НАСТРОЙКИ_ПО_УМОЛЧАНИЮ };

    const разобранное = JSON.parse(сырое) as Partial<НастройкиПриложения>;
    return нормализоватьНастройки({
      ...НАСТРОЙКИ_ПО_УМОЛЧАНИЮ,
      ...разобранное,
    });
  } catch (ошибка) {
    логгер.предупреждение('Не удалось прочитать настройки', ошибка);
    return { ...НАСТРОЙКИ_ПО_УМОЛЧАНИЮ };
  }
}

export function сохранитьНастройки(настройки: НастройкиПриложения): void {
  try {
    const нормализованные = нормализоватьНастройки(настройки);
    localStorage.setItem(КЛЮЧ, JSON.stringify(нормализованные));
  } catch (ошибка) {
    логгер.предупреждение('Не удалось сохранить настройки', ошибка);
  }
}

function нормализоватьСтраницу(значение: unknown): СтраницаПриложения {
  return значение === 'мульти' ? 'мульти' : 'инспектор';
}

export function нормализоватьНастройки(
  настройки: НастройкиПриложения,
): НастройкиПриложения {
  return {
    прозрачностьРазметки: ограничить(настройки.прозрачностьРазметки, 0, 1),
    показыватьТекст: Boolean(настройки.показыватьТекст),
    показыватьИзображения: Boolean(настройки.показыватьИзображения),
    масштаб: ограничить(настройки.масштаб, 0.5, 3),
    номерСтраницы: Math.max(1, Math.floor(настройки.номерСтраницы || 1)),
    страница: нормализоватьСтраницу(настройки.страница),
    линейкаВключена: Boolean(настройки.линейкаВключена),
    прозрачностьСлояКартинки: ограничить(
      настройки.прозрачностьСлояКартинки ?? 0.55,
      0,
      1,
    ),
  };
}
