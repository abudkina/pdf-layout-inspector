import {
  ДОПУСТИМЫЕ_ТИПЫ,
  МАКС_РАЗМЕР_ФАЙЛА,
  type РезультатВалидации,
} from '../types';

/**
 * Проверяет загружаемый файл: тип, размер, расширение.
 */
export function проверитьФайл(файл: File): РезультатВалидации {
  if (!файл) {
    return { ок: false, ошибка: 'Файл не выбран. Выберите PDF-документ.' };
  }

  if (файл.size === 0) {
    return {
      ок: false,
      ошибка: 'Файл пуст. Загрузите корректный PDF-документ.',
    };
  }

  if (файл.size > МАКС_РАЗМЕР_ФАЙЛА) {
    const мб = (МАКС_РАЗМЕР_ФАЙЛА / (1024 * 1024)).toFixed(0);
    return {
      ок: false,
      ошибка: `Файл слишком большой. Максимальный размер — ${мб} МБ.`,
    };
  }

  const имя = файл.name.toLowerCase();
  const расширениеОк = имя.endsWith('.pdf');
  const типОк =
    !файл.type ||
    ДОПУСТИМЫЕ_ТИПЫ.includes(файл.type as (typeof ДОПУСТИМЫЕ_ТИПЫ)[number]);

  if (!расширениеОк && !типОк) {
    return {
      ок: false,
      ошибка: 'Неверный формат. Загрузите файл с расширением .pdf.',
    };
  }

  if (!расширениеОк) {
    return {
      ок: false,
      ошибка: 'Имя файла должно заканчиваться на .pdf.',
    };
  }

  return { ок: true };
}

/**
 * Проверяет, что буфер начинается с сигнатуры %PDF-
 */
export function проверитьСигнатуруPdf(буфер: ArrayBuffer): РезультатВалидации {
  if (!буфер || буфер.byteLength < 5) {
    return {
      ок: false,
      ошибка: 'Файл повреждён или слишком короткий для PDF.',
    };
  }

  const байты = new Uint8Array(буфер.slice(0, 8));
  const сигнатура = String.fromCharCode(...байты.slice(0, 5));

  if (сигнатура !== '%PDF-') {
    return {
      ок: false,
      ошибка:
        'Файл не является PDF: отсутствует сигнатура %PDF-. Проверьте целостность документа.',
    };
  }

  return { ок: true };
}

/**
 * Валидация URL для загрузки удалённого PDF.
 */
export function проверитьUrl(строка: string): РезультатВалидации {
  const обрезанная = строка.trim();

  if (!обрезанная) {
    return { ок: false, ошибка: 'Введите адрес PDF-документа.' };
  }

  let url: URL;
  try {
    url = new URL(обрезанная);
  } catch {
    return {
      ок: false,
      ошибка: 'Некорректный адрес. Укажите полный URL, например https://пример.рф/файл.pdf',
    };
  }

  if (url.protocol !== 'http:' && url.protocol !== 'https:') {
    return {
      ок: false,
      ошибка: 'Допускаются только протоколы http и https.',
    };
  }

  return { ок: true };
}

/**
 * Ограничивает число в диапазоне [мин, макс].
 */
export function ограничить(значение: number, мин: number, макс: number): number {
  if (Number.isNaN(значение)) return мин;
  return Math.min(макс, Math.max(мин, значение));
}

/**
 * Парсит прозрачность из строки слайдера (0–100 → 0–1).
 */
export function прозрачностьИзПроцентов(проценты: number): number {
  return ограничить(проценты, 0, 100) / 100;
}

/**
 * Проценты из прозрачности (0–1 → 0–100).
 */
export function процентыИзПрозрачности(прозрачность: number): number {
  return Math.round(ограничить(прозрачность, 0, 1) * 100);
}
