/**
 * Web Worker: постобработка разметки (фильтрация шумов, нормализация).
 * Тяжёлые вычисления вынесены из основного потока.
 */

import type {
  РазметкаСтраницы,
  СообщениеВоркерЗапрос,
  СообщениеВоркерОтвет,
  ТекстовыйБлок,
  БлокИзображения,
} from '../types';
import { площадь } from '../utils/geometry';

const МИН_ПЛОЩАДЬ_ТЕКСТА = 4;
const МИН_ПЛОЩАДЬ_ИЗОБРАЖЕНИЯ = 100;

self.onmessage = (событие: MessageEvent<СообщениеВоркерЗапрос>) => {
  const данные = событие.data;

  if (данные.тип !== 'обработать-разметку') {
    const ответ: СообщениеВоркерОтвет = {
      тип: 'ошибка',
      сообщение: 'Неизвестный тип сообщения воркера.',
    };
    self.postMessage(ответ);
    return;
  }

  try {
    const обработанные = данные.страницы.map((страница) =>
      обработатьСтраницу(страница),
    );
    const ответ: СообщениеВоркерОтвет = {
      тип: 'разметка-готова',
      страницы: обработанные,
    };
    self.postMessage(ответ);
  } catch (ошибка) {
    const ответ: СообщениеВоркерОтвет = {
      тип: 'ошибка',
      сообщение:
        ошибка instanceof Error
          ? ошибка.message
          : 'Ошибка обработки разметки в воркере.',
    };
    self.postMessage(ответ);
  }
};

function обработатьСтраницу(страница: РазметкаСтраницы): РазметкаСтраницы {
  return {
    ...страница,
    тексты: отфильтроватьТексты(страница.тексты),
    изображения: отфильтроватьИзображения(страница.изображения),
  };
}

function отфильтроватьТексты(блоки: ТекстовыйБлок[]): ТекстовыйБлок[] {
  return блоки.filter((блок) => {
    if (!блок.текст.trim()) return false;
    if (площадь(блок.прямоугольник) < МИН_ПЛОЩАДЬ_ТЕКСТА) return false;
    if (блок.прямоугольник.ширина <= 0 || блок.прямоугольник.высота <= 0) {
      return false;
    }
    return true;
  });
}

function отфильтроватьИзображения(
  блоки: БлокИзображения[],
): БлокИзображения[] {
  return блоки.filter((блок) => площадь(блок.прямоугольник) >= МИН_ПЛОЩАДЬ_ИЗОБРАЖЕНИЯ);
}
