/** Типы доменной модели PDF Layout Inspector */

/** Прямоугольник в CSS-пикселях относительно страницы */
export interface Прямоугольник {
  x: number;
  y: number;
  ширина: number;
  высота: number;
}

/** Информация о шрифте текстового элемента */
export interface ИнфоШрифта {
  семейство: string;
  размер: number;
  вес?: string;
  стиль?: string;
}

/** Текстовый блок, извлечённый из PDF */
export interface ТекстовыйБлок {
  id: string;
  текст: string;
  прямоугольник: Прямоугольник;
  шрифт: ИнфоШрифта;
  уголПоворота: number;
  страница: number;
}

/** Изображение (или XObject), найденное на странице */
export interface БлокИзображения {
  id: string;
  прямоугольник: Прямоугольник;
  страница: number;
  ширинаИсходная?: number;
  высотаИсходная?: number;
}

/** Результат разбора одной страницы */
export interface РазметкаСтраницы {
  номер: number;
  ширина: number;
  высота: number;
  тексты: ТекстовыйБлок[];
  изображения: БлокИзображения[];
}

/** Полный документ после разбора */
export interface РазметкаДокумента {
  имяФайла: string;
  числоСтраниц: number;
  страницы: РазметкаСтраницы[];
}

/** Раздел интерфейса */
export type СтраницаПриложения = 'инспектор' | 'мульти';

/** Настройки интерфейса, хранящиеся локально */
export interface НастройкиПриложения {
  прозрачностьРазметки: number;
  показыватьТекст: boolean;
  показыватьИзображения: boolean;
  масштаб: number;
  номерСтраницы: number;
  страница: СтраницаПриложения;
  линейкаВключена: boolean;
  прозрачностьСлояКартинки: number;
}

/** Сообщение для Web Worker: запрос на обработку геометрии */
export interface СообщениеВоркерЗапрос {
  тип: 'обработать-разметку';
  страницы: РазметкаСтраницы[];
  масштаб: number;
}

/** Ответ Web Worker */
export interface СообщениеВоркерОтвет {
  тип: 'разметка-готова' | 'ошибка';
  страницы?: РазметкаСтраницы[];
  сообщение?: string;
}

/** Результат валидации файла */
export interface РезультатВалидации {
  ок: boolean;
  ошибка?: string;
}

