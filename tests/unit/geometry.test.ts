import { describe, it, expect } from 'vitest';
import {
  пересекаются,
  точкаВнутри,
  масштабироватьПрямоугольник,
  площадь,
  размерШрифтаИзTransform,
  округлить,
  блокиНаОднойСтроке,
  расстояние,
  форматИзмерения,
} from '../../src/utils/geometry';

describe('геометрия', () => {
  const a = { x: 0, y: 0, ширина: 10, высота: 10 };
  const b = { x: 5, y: 5, ширина: 10, высота: 10 };
  const c = { x: 20, y: 20, ширина: 5, высота: 5 };

  it('пересекаются', () => {
    expect(пересекаются(a, b)).toBe(true);
    expect(пересекаются(a, c)).toBe(false);
  });

  it('точкаВнутри', () => {
    expect(точкаВнутри(5, 5, a)).toBe(true);
    expect(точкаВнутри(15, 5, a)).toBe(false);
  });

  it('масштабироватьПрямоугольник', () => {
    const r = масштабироватьПрямоугольник(a, 2);
    expect(r).toEqual({ x: 0, y: 0, ширина: 20, высота: 20 });
  });

  it('площадь', () => {
    expect(площадь(a)).toBe(100);
    expect(площадь({ x: 0, y: 0, ширина: -1, высота: 5 })).toBe(0);
  });

  it('размерШрифтаИзTransform', () => {
    expect(размерШрифтаИзTransform([12, 0, 0, 12, 0, 0])).toBeCloseTo(12);
    expect(размерШрифтаИзTransform([0, 10, -10, 0, 0, 0])).toBeCloseTo(10);
  });

  it('округлить', () => {
    expect(округлить(1.2345, 2)).toBe(1.23);
    expect(округлить(1.235, 2)).toBe(1.24);
  });

  it('блокиНаОднойСтроке', () => {
    const s1 = { x: 0, y: 10, ширина: 20, высота: 12 };
    const s2 = { x: 25, y: 11, ширина: 30, высота: 12 };
    const s3 = { x: 0, y: 40, ширина: 20, высота: 12 };
    expect(блокиНаОднойСтроке(s1, s2)).toBe(true);
    expect(блокиНаОднойСтроке(s1, s3)).toBe(false);
  });

  it('расстояние и форматИзмерения', () => {
    expect(расстояние(0, 0, 3, 4)).toBe(5);
    const изм = форматИзмерения(125, 1.25);
    expect(изм.пиксели).toBe(125);
    expect(изм.пункты).toBe(100);
    expect(изм.мм).toBeCloseTo(35.28, 1);
    expect(изм.текст).toMatch(/px/);
    expect(изм.текст).toMatch(/pt/);
    expect(изм.текст).toMatch(/мм/);
  });
});
