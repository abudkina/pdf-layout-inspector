import { describe, it, expect, beforeEach } from 'vitest';
import {
  загрузитьНастройки,
  сохранитьНастройки,
  нормализоватьНастройки,
} from '../../src/utils/storage';
import { НАСТРОЙКИ_ПО_УМОЛЧАНИЮ } from '../../src/types';

describe('хранилище настроек', () => {
  beforeEach(() => {
    localStorage.clear();
  });

  it('возвращает значения по умолчанию', () => {
    expect(загрузитьНастройки()).toEqual(НАСТРОЙКИ_ПО_УМОЛЧАНИЮ);
  });

  it('сохраняет и читает настройки', () => {
    const настройки = {
      ...НАСТРОЙКИ_ПО_УМОЛЧАНИЮ,
      прозрачностьРазметки: 0.5,
      масштаб: 1.5,
    };
    сохранитьНастройки(настройки);
    expect(загрузитьНастройки().прозрачностьРазметки).toBe(0.5);
    expect(загрузитьНастройки().масштаб).toBe(1.5);
  });

  it('нормализует выход за границы', () => {
    const н = нормализоватьНастройки({
      ...НАСТРОЙКИ_ПО_УМОЛЧАНИЮ,
      прозрачностьРазметки: 2,
      масштаб: 0.1,
      номерСтраницы: -5,
      прозрачностьСлояКартинки: 5,
      страница: 'мульти',
    });
    expect(н.прозрачностьРазметки).toBe(1);
    expect(н.масштаб).toBe(0.5);
    expect(н.номерСтраницы).toBe(1);
    expect(н.прозрачностьСлояКартинки).toBe(1);
    expect(н.страница).toBe('мульти');
  });

  it('игнорирует битый JSON', () => {
    localStorage.setItem('pdf-layout-inspector:настройки', '{не json');
    expect(загрузитьНастройки()).toEqual(НАСТРОЙКИ_ПО_УМОЛЧАНИЮ);
  });
});
