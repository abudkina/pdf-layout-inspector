import { describe, it, expect } from 'vitest';
import { площадь } from '../../src/utils/geometry';
import type { ТекстовыйБлок, БлокИзображения } from '../../src/types';

/** Логика фильтрации воркера (дублируем пороги для unit без Worker) */
const МИН_ПЛОЩАДЬ_ТЕКСТА = 4;
const МИН_ПЛОЩАДЬ_ИЗОБРАЖЕНИЯ = 100;

function отфильтроватьТексты(блоки: ТекстовыйБлок[]): ТекстовыйБлок[] {
  return блоки.filter((блок) => {
    if (!блок.текст.trim()) return false;
    if (площадь(блок.прямоугольник) < МИН_ПЛОЩАДЬ_ТЕКСТА) return false;
    if (блок.прямоугольник.ширина <= 0 || блок.прямоугольник.высота <= 0) {
      return false;
    }
    return true;
  });
}

function отфильтроватьИзображения(
  блоки: БлокИзображения[],
): БлокИзображения[] {
  return блоки.filter(
    (блок) => площадь(блок.прямоугольник) >= МИН_ПЛОЩАДЬ_ИЗОБРАЖЕНИЯ,
  );
}

function блокТекста(
  текст: string,
  w: number,
  h: number,
): ТекстовыйБлок {
  return {
    id: 'т-1',
    текст,
    прямоугольник: { x: 0, y: 0, ширина: w, высота: h },
    шрифт: { семейство: 'Arial', размер: 12 },
    уголПоворота: 0,
    страница: 1,
  };
}

describe('фильтрация разметки (воркер)', () => {
  it('убирает пустой и крошечный текст', () => {
    const вход = [
      блокТекста('Привет', 40, 14),
      блокТекста('   ', 40, 14),
      блокТекста('x', 1, 1),
    ];
    const выход = отфильтроватьТексты(вход);
    expect(выход).toHaveLength(1);
    expect(выход[0].текст).toBe('Привет');
  });

  it('убирает мелкие изображения-шум', () => {
    const вход: БлокИзображения[] = [
      {
        id: 'и-1',
        прямоугольник: { x: 0, y: 0, ширина: 5, высота: 5 },
        страница: 1,
      },
      {
        id: 'и-2',
        прямоугольник: { x: 0, y: 0, ширина: 200, высота: 100 },
        страница: 1,
      },
    ];
    expect(отфильтроватьИзображения(вход)).toHaveLength(1);
  });
});
